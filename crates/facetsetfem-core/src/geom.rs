//! 3 次元ベクトルの小さな演算（要素・面・流線などで共通に使う）。
//!
//! 以前は同じ関数が要素・面積分・ポスト処理のファイルごとに書かれていた。
//!
//! **式の形（加算の順序）を変えてはいけない。** 浮動小数点の加算は結合則が
//! 成り立たないので、`a0 b0 + a1 b1 + a2 b2` を別の順に書き換えると最下位ビットが
//! 変わり、これまでの結果とビット単位で一致しなくなる（CLAUDE.md 設計原則 1）。

/// `a − b`
#[inline]
pub(crate) fn sub(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

/// 外積 `a × b`
#[inline]
pub(crate) fn cross(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

/// 内積 `a · b`（成分 0 → 1 → 2 の順に足す）
#[inline]
pub(crate) fn dot(a: [f64; 3], b: [f64; 3]) -> f64 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

/// 長さ `|a|`
#[inline]
pub(crate) fn norm(a: [f64; 3]) -> f64 {
    dot(a, a).sqrt()
}

/// スカラー倍 `a s`
#[inline]
pub(crate) fn scale(a: [f64; 3], s: f64) -> [f64; 3] {
    [a[0] * s, a[1] * s, a[2] * s]
}
